/* =================== THE IRISH PLACE DATABASE ===================

   WHAT THIS FILE IS. Every settlement, townland, suburb, postal district and
   automotive node the page can offer in its location field, and nothing else.
   It was cut out of allparts-rfq-prototype-v2.html on 1 October 2026 and is
   loaded as a plain classic script, before the page's own script:

       <script src="./ireland-locations-db.js"></script>

   Three pages load it that way: v2, v4-STABLE and v4-solo. Only v4-STABLE
   folds in its own extra batch and this file's batch 5; the other two read the
   rows declared here and stop, because their own scripts predate batch 5 and
   have no call that mentions it. That is a known gap, not an oversight: those
   two pages are older builds, and adding a merge call to them would be an edit
   to files that are deliberately not being touched.

   The v2 in that list is the working build, NOT v2-STABLE. v2-STABLE does not
   load this file at all: the strings "ireland-locations-db" and "IRISH_PLACES"
   do not occur in it even once, so it carries its own older inlined copy and
   sees none of batches 2, 3 or 5. It was named here by mistake in an earlier
   draft of this header, which is worth writing down because a header that
   misnames its consumers sends the next person to edit a file that was never
   loading anything.

   WHY IT IS A SEPARATE FILE. The dataset is the largest single thing in the
   product and it is the part that changes most often -- upstream sends it in
   batches -- so it was the part worth taking out of the view and out of the
   context every edit to the interface has to read. Nothing here is behaviour:
   the merge, the county placeholder resolver and the search layer all stayed
   in the page, and this file is the data they read.

   HOW IT IS ASSEMBLED. IRISH_PLACES is the base, 191 rows of
   [name, county, gaelic name, streets]. PLACE_BATCH_2, PLACE_BATCH_3 and
   PLACE_BATCH_5 -- the last one at the foot of this file, the city district
   delivery -- are three upstream batches, each row {name, county, type}, and
   the page folds them in with mergePlaceRows(), which appends and never edits.
   The array the rest of the page sees is therefore 1664 rows and is built at
   load; v4 folds in its own one-row batch 4 on top and sees 1665.

   Those numbers were MEASURED, not added up, by running the page's own
   mergePlaceRows over this file. The arithmetic is not the sum of the declared
   row counts: batch 2 declares 83 rows and adds 79, because four of its rows
   are already in the base and only gain their type, so 191 + 83 + 1276 + 118
   reads 18 too high. Anyone who needs the real count should run the merge and
   read report.after, which is what placeMergeReport and its siblings print.

   THE type COLUMN. Index 4 of a base row, and the `type` of a batch row. It
   is stored and not rendered: `sub` on a suggestion row is the county, and a
   suggestion row is 44px tall in a list capped at seven in a 460px column. The
   dataset grew a column the UI does not yet print, and that is stated here
   rather than dressed up as a feature.

   NOTHING HERE IS PLACEHOLDER TEXT. Both county tables below exist to resolve
   the one non-county the upstream feeds carry, "Ireland (ROI)", and the merge
   is told loudly when a row arrives with a county it cannot resolve rather than
   being given a plausible wrong one.

   ENCODING. UTF-8, no BOM, CRLF, exactly as the page it came out of.
   ==================================================================== */

